---@param entity integer
local function applyAttributes(entity)
    SetEntityCanBeDamaged(entity, false)
    SetPedAsEnemy(entity, false)
    SetBlockingOfNonTemporaryEvents(entity, true)
    SetPedResetFlag(entity, 249, true)
    SetPedConfigFlag(entity, 185, true)
    SetPedConfigFlag(entity, 108, true)
    SetPedCanEvasiveDive(entity, false)
    SetPedCanRagdollFromPlayerImpact(entity, false)
    SetPedConfigFlag(entity, 208, true)
    SetEntityCollision(entity, false, false)
    FreezeEntityPosition(entity, true)
end

local SetPedComponentVariation = SetPedComponentVariation
---@param entity integer
---@param components integer[][]
local function applyOutfitComponents(entity, components)
    for i = 1, #components do
        local comp = components[i]
        SetPedComponentVariation(entity, comp[1], comp[2], comp[3], comp[4])
    end
end

local SpawnDealer = {}

for k, v in pairs(dealerOutfits) do
    SpawnDealer[k] = function(coords)
        lib.requestModel(v.model)
        local entity = CreatePed(4, v.model, coords.x, coords.y, coords.z, coords.w, false, false)
        applyAttributes(entity)
        SetPedDefaultComponentVariation(entity)
        applyOutfitComponents(entity, v.components)
        if v.prop then
            SetPedPropIndex(entity, v.prop[1], v.prop[2], v.prop[3], v.prop[4])
        end
        SetPedVoiceGroup(entity, v.voice)
        SetModelAsNoLongerNeeded(v.model)
        return entity
    end
end

return SpawnDealer